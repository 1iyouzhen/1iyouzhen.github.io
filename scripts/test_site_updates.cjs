const {chromium}=require('../.tools/browser/node_modules/playwright-core');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
 const context=await browser.newContext({viewport:{width:1200,height:900}});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base='http://127.0.0.1:8876';
 await page.goto(base+'/zh/',{waitUntil:'networkidle'});
 assert.equal(await page.locator('#check-site-update').count(),1);
 const current=await page.locator('meta[name="blog-revision"]').getAttribute('content');
 assert.match(current,/^[a-f0-9]{40}$/);
 assert.ok((await page.locator('.post-entry').allTextContents()).some(x=>x.includes('我的第一篇文章')));
 await page.locator('#check-site-update').click();
 await page.waitForURL(url=>url.searchParams.get('_release')===current&&url.searchParams.has('_refresh'));
 await page.waitForLoadState('networkidle');
 await page.goto(base+'/zh/search/',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>!document.querySelector('#searchInput').disabled);
 await page.locator('#searchInput').fill('我的第一篇文章');
 await page.waitForFunction(()=>document.querySelector('#searchResults')?.textContent.includes('我的第一篇文章'));
 const requestIndex=await page.evaluate(()=>performance.getEntriesByType('resource').find(x=>x.name.includes('/index.json')&&x.initiatorType==='fetch')?.name);
 assert.ok(requestIndex.includes('_release='));
 assert.ok(requestIndex.includes('_time='));
 const next='a'.repeat(40);let checks=0;
 await page.route('**/deployment.json?*',route=>{checks++;return route.fulfill({contentType:'application/json',body:JSON.stringify({revision:next,builtAt:'2099-01-01T00:00:00Z'})})});
 await page.goto(base+'/zh/',{waitUntil:'networkidle'});
 await page.waitForURL(url=>url.searchParams.get('_release')===next,{timeout:10000});
 await page.waitForLoadState('networkidle');
 await page.waitForTimeout(1500);
 assert.ok(checks<=3,'Version checks should not create a refresh loop');
 assert.deepEqual(errors,[]);
 await page.screenshot({path:'.tools/update-controls.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 console.log(JSON.stringify({status:'PASS',versionButton:true,manualCacheRefresh:true,automaticNewVersionRefresh:true,noReloadLoop:true,freshSearchIndex:true,userArticleSearchable:true,consoleErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
