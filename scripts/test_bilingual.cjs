const {chromium}=require('../.tools/browser/node_modules/playwright-core');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.BLOG_URL || 'http://127.0.0.1:8878';
 const pairs=[['/zh/','/'],['/zh/about/','/about/'],['/zh/projects/','/projects/'],['/zh/archives/','/archives/'],['/zh/search/','/search/'],['/zh/tags/','/tags/'],['/zh/posts/hello-world/','/posts/hello-world/'],['/zh/posts/my-first-post/','/posts/my-first-post/'],['/zh/posts/learning-map/','/posts/learning-map/']];
 await page.goto(base+'/',{waitUntil:'networkidle'});
 assert.equal(await page.locator('html').getAttribute('lang'),'en-US');
 assert.equal(await page.locator('#language-toggle').innerText(),'English');
 assert.equal(await page.locator('#language-toggle').getAttribute('aria-expanded'),'false');
 assert.ok(!(await page.locator('#language-options').isVisible()));
 await page.locator('#language-toggle').click();
 assert.equal(await page.locator('#language-toggle').getAttribute('aria-expanded'),'true');
 assert.ok(await page.locator('#language-options').isVisible());
 assert.deepEqual(await page.locator('#language-options a span').allTextContents(),['English','简体中文']);
 await page.keyboard.press('Escape');
 assert.ok(!(await page.locator('#language-options').isVisible()));
 assert.equal(await page.locator('#language-toggle').evaluate(el=>el===document.activeElement),true);
 await page.keyboard.press('ArrowDown');
 assert.ok(await page.locator('#language-options').isVisible());
 assert.equal(await page.locator('#language-options a.is-active').evaluate(el=>el===document.activeElement),true);
 await page.keyboard.press('ArrowDown');
 assert.equal(await page.locator('#language-options a[data-language=zh]').evaluate(el=>el===document.activeElement),true);
 await page.keyboard.press('Escape');
 await page.locator('#language-toggle').click();
 await page.locator('main h1').click();
 assert.ok(!(await page.locator('#language-options').isVisible()));
 for(const [zh,en] of pairs){
  await page.goto(base+en,{waitUntil:'networkidle'});
  assert.equal(await page.locator('html').getAttribute('lang'),'en-US');
  assert.equal(await page.locator('.language-switcher a[data-language=zh]').getAttribute('href'),zh);
  assert.ok(!(await page.locator('#language-options').isVisible()));
  const text=(await page.locator('main').innerText()).replaceAll('简体中文','');
  assert.ok(!/[\u4e00-\u9fff]/.test(text),'Mixed English content: '+en);
  await page.locator('#language-toggle').click();
  await page.locator('.language-switcher a[data-language=zh]').click();
  await page.waitForLoadState('networkidle');
  assert.equal(new URL(page.url()).pathname,zh);
  assert.equal(await page.locator('html').getAttribute('lang'),'zh-CN');
  assert.equal(await page.locator('#language-toggle').innerText(),'简体中文');
  assert.equal(await page.locator('.language-switcher a[data-language=en]').getAttribute('href'),en);
  await page.locator('#language-toggle').click();
  await page.locator('.language-switcher a[data-language=en]').click();
  await page.waitForLoadState('networkidle');
  assert.equal(new URL(page.url()).pathname,en);
 }
 await page.goto(base+'/search/',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>!document.querySelector('#searchInput').disabled);
 await page.locator('#searchInput').fill('My First Article');
 await page.waitForFunction(()=>document.querySelector('#searchResults').textContent.includes('My First Article'));
 assert.ok((await page.locator('#searchResults a').evaluateAll(a=>a.map(x=>new URL(x.href).pathname))).every(x=>!x.startsWith('/zh/')));
 await page.goto(base+'/zh/search/',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>!document.querySelector('#searchInput').disabled);
 await page.locator('#searchInput').fill('我的第一篇文章');
 await page.waitForFunction(()=>document.querySelector('#searchResults').textContent.includes('我的第一篇文章'));
 assert.ok((await page.locator('#searchResults a').evaluateAll(a=>a.map(x=>new URL(x.href).pathname))).every(x=>x.startsWith('/zh/')));
 await page.goto(base+'/en/posts/hello-world/',{waitUntil:'networkidle'});
 await page.waitForURL(url=>url.pathname==='/posts/hello-world/');
 assert.equal(await page.locator('html').getAttribute('lang'),'en-US');
 await page.locator('#theme-toggle').click();
 await page.locator('#language-toggle').click();
 await page.locator('#language-options a[data-language=zh]').click();
 await page.waitForLoadState('networkidle');
 assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
 await page.locator('#theme-toggle').click();
 for(const width of [390,320]){
  await page.setViewportSize({width,height:844});
  for(const route of ['/','/zh/','/posts/hello-world/']){
   await page.goto(base+route,{waitUntil:'networkidle'});
   await page.locator('#language-toggle').click();
   assert.ok(await page.locator('#language-options a[data-language=zh]').isVisible());
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile overflow: '+route+' at '+width);
   const box=await page.locator('#language-options').boundingBox();
   assert.ok(box.x>=0&&box.x+box.width<=width+1);
  }
 }
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'/',{waitUntil:'networkidle'});
 await page.screenshot({path:'.tools/english-default.png',fullPage:true});
 await page.locator('#language-toggle').click();
 await page.screenshot({path:'.tools/language-dropdown.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({status:'PASS',englishDefault:true,dropdownHiddenInitially:true,dropdownClick:true,escapeAndKeyboard:true,outsideDismiss:true,translationPairs:pairs.length,separateSearch:true,legacyEnglishRedirect:true,mobileWidths:[390,320],consoleErrors:errors}));
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
